#!/usr/bin/env node
/* Vercel build step: injects API_BASE into frontend/js/config.js.
   FAILS THE BUILD if API_BASE is missing or unsafe, so a production deploy can never silently
   fall back to localhost or to same-origin requests. API_BASE is a public URL, not a secret. */
const fs = require("fs"), path = require("path");
const out = path.join(__dirname, "..", "frontend", "js", "config.js");
const fail = m => { console.error("\n[build-frontend] ERROR: " + m + "\n"); process.exit(1); };
const raw = (process.env.API_BASE || "").trim();
if (!raw) fail("API_BASE is not set. In Vercel: Project → Settings → Environment Variables → API_BASE = https://<your-service>.onrender.com (all environments), then redeploy.");
let u; try { u = new URL(raw); } catch { fail("API_BASE is not a valid URL: " + raw); }
if (u.protocol !== "https:") fail("API_BASE must use https (browsers block http APIs from an https page): " + raw);
if (["localhost", "127.0.0.1", "[::1]"].includes(u.hostname)) fail("API_BASE points to localhost, which can never work in production: " + raw);
if ((u.pathname !== "/" && u.pathname !== "") || u.search || u.hash || u.username || u.password) fail("API_BASE must be an origin only (https://host), no path, query or credentials: " + raw);
fs.writeFileSync(out, "// generated by scripts/build-frontend.js — do not edit\nwindow.API_BASE = " + JSON.stringify(u.origin) + ";\n");
console.log("[build-frontend] API_BASE = " + u.origin);
